/* =====================================================
   Sitemap Generator – frontend logic
   =====================================================
   Implements all Pro-sitemaps.com features in the browser:
     - ISO 8601 lastmod display
     - Export toolbar (XML / HTML / CSV / TXT / .gz)
     - Tab strip (URLs / Images / Videos / News / Reports)
     - Reports renderer (broken / redirect / orphan / duplicates / link analysis)
     - Validation banner
     - robots.txt + public URL copy
   ===================================================== */
(function () {
    'use strict';

    // ─── shared state across both Quick + Client mode ────────────────────
    let lastClientId = null;
    let lastSavedId  = null;
    let lastXml      = '';
    let lastStats    = null;
    let lastSiteUrl  = null;
    let activeTab    = 'urls';

    const $ = id => document.getElementById(id);

    // ─── helper: robots.txt preview ───────────────────────────────────────
    function buildRobotsTxt(siteUrl, sitemapUrl) {
        return [
            'User-agent: *',
            'Allow: /',
            '',
            `# Sitemap generated by Keyword Analyzer`,
            `Sitemap: ${sitemapUrl}`,
        ].join('\n');
    }

    // ─── helper: render summary chips ─────────────────────────────────────
    function renderSummary(target, stats) {
        if (!target || !stats) return;
        const skipped = stats.skipped || {};
        const blocks = [
            `<span><strong>${(stats.crawled || 0).toLocaleString()}</strong> URLs crawled</span>`,
            skipped.robots != null ? `<span><strong>${skipped.robots}</strong> blocked by robots</span>` : '',
            skipped.noindex != null ? `<span><strong>${skipped.noindex}</strong> noindex</span>` : '',
            skipped.error   != null ? `<span><strong>${skipped.error}</strong> errors</span>` : '',
            skipped.canonical != null ? `<span><strong>${skipped.canonical}</strong> canonical dup</span>` : '',
            stats.totalLinks != null ? `<span><strong>${stats.totalLinks.toLocaleString()}</strong> internal links</span>` : '',
            stats.durationMs != null ? `<span>in <strong>${(stats.durationMs/1000).toFixed(1)}s</strong></span>` : '',
        ].filter(Boolean);
        target.innerHTML = blocks.join('');
    }

    // ─── helper: render image grid ────────────────────────────────────────
    function renderImageGrid(target, urls) {
        if (!target) return;
        if (!urls || urls.length === 0) {
            target.innerHTML = '<div class="sitemap-empty">No images found. Re-crawl with images enabled.</div>';
            return;
        }
        const items = urls.slice(0, 60);
        target.innerHTML = items.map(u => `
            <div class="sitemap-image-card">
                <img src="${escAttr(u.loc)}" alt="" loading="lazy" onerror="this.style.display='none'">
                <div class="sitemap-image-caption">${escHtml(u.title || u.loc)}</div>
            </div>`).join('');
        if (urls.length > items.length) {
            target.innerHTML += `<div class="sitemap-empty">+ ${urls.length - items.length} more images not shown</div>`;
        }
    }

    // ─── helper: render video list ────────────────────────────────────────
    function renderVideoList(target, urls) {
        if (!target) return;
        if (!urls || urls.length === 0) {
            target.innerHTML = '<div class="sitemap-empty">No videos detected.</div>';
            return;
        }
        target.innerHTML = urls.map(v => `
            <div class="sitemap-video-card">
                <h4>${escHtml(v.title || v.contentLoc || v.playerLoc || 'Video')}</h4>
                <div class="meta">${v.contentLoc ? `<i class="fas fa-link"></i> ${escHtml(v.contentLoc)}` : ''}${v.playerLoc ? ` · <i class="fas fa-play"></i> ${escHtml(v.playerLoc)}` : ''}</div>
                ${v.thumbnailLoc ? `<img src="${escAttr(v.thumbnailLoc)}" alt="" loading="lazy" onerror="this.style.display='none'">` : ''}
            </div>`).join('');
    }

    // ─── helper: render news list ─────────────────────────────────────────
    function renderNewsList(target, urls) {
        if (!target) return;
        if (!urls || urls.length === 0) {
            target.innerHTML = '<div class="sitemap-empty">No news articles detected.</div>';
            return;
        }
        target.innerHTML = urls.map(n => `
            <div class="sitemap-news-card">
                <h4>${escHtml(n.title || 'Untitled')}</h4>
                <div class="meta">${escHtml(n.publicationName || 'Unknown source')} · ${escHtml(n.publicationDate || '')} · ${escHtml(n.language || '')}</div>
                ${n.keywords ? `<div class="meta" style="margin-top:4px">${escHtml(n.keywords)}</div>` : ''}
            </div>`).join('');
    }

    // ─── helper: report cards ─────────────────────────────────────────────
    function buildReportCard(title, badge, isOk, bodyHtml) {
        return `<div class="sitemap-report-card">
            <div class="sitemap-report-card-header ${isOk ? 'ok' : ''}">
                ${title}
                <span class="count-badge">${badge}</span>
            </div>
            <div class="sitemap-report-card-body">${bodyHtml}</div>
        </div>`;
    }

    function escHtml(s) {
        return String(s == null ? '' : s)
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#39;');
    }
    function escAttr(s) { return escHtml(s); }

    function renderReports(target, data) {
        if (!target) return;
        const r = data.reports || {};
        const cards = [];

        // Validation banner
        if (data.validation) {
            const v = data.validation;
            const cls = !v.ok ? 'error' : (v.warnings && v.warnings.length ? 'warn' : 'ok');
            const head = !v.ok ? `❌ ${v.errors.length} error${v.errors.length !== 1 ? 's' : ''}` :
                v.warnings && v.warnings.length ? `⚠️ ${v.warnings.length} warning${v.warnings.length !== 1 ? 's' : ''}` :
                '✅ Sitemap passes Google spec checks';
            const list = [...(v.errors || []), ...(v.warnings || []), ...(v.notes || [])]
                .slice(0, 20)
                .map(item => `<li>${escHtml(item.message || item.code || '')}</li>`).join('');
            cards.push(`<div class="sitemap-validation-banner ${cls}"><strong>${head}</strong>${list ? `<ul>${list}</ul>` : ''}</div>`);
        }

        // Broken links
        const broken = r.brokenLinks || [];
        cards.push(buildReportCard(
            '⚠️ Broken links', broken.length, broken.length === 0,
            broken.length === 0
                ? '<div class="empty">No broken links detected.</div>'
                : `<table><thead><tr><th>Status</th><th>URL</th></tr></thead><tbody>${
                    broken.slice(0, 100).map(b => `<tr><td class="status-${String(b.status).charAt(0)}xx">${b.status}</td><td><a href="${escAttr(b.url)}" target="_blank" rel="noopener">${escHtml(b.url)}</a></td></tr>`).join('')
                }</tbody></table>`
        ));

        // Redirects
        const redirects = r.redirects || [];
        cards.push(buildReportCard(
            '↪️ Redirects', redirects.length, redirects.length === 0,
            redirects.length === 0
                ? '<div class="empty">No redirects found.</div>'
                : `<table><thead><tr><th>Start</th><th>Hops</th></tr></thead><tbody>${
                    redirects.slice(0, 100).map(d => `<tr><td><a href="${escAttr(d.startUrl)}" target="_blank" rel="noopener">${escHtml(d.startUrl)}</a></td><td>${d.hopCount}</td></tr>`).join('')
                }</tbody></table>`
        ));

        // Blocked by robots
        const blocked = r.blocked || [];
        cards.push(buildReportCard(
            '🤖 Blocked by robots.txt', blocked.length, blocked.length === 0,
            blocked.length === 0
                ? '<div class="empty">No URLs blocked.</div>'
                : `<table><thead><tr><th>URL</th></tr></thead><tbody>${
                    blocked.slice(0, 100).map(b => `<tr><td>${escHtml(b.url)}</td></tr>`).join('')
                }</tbody></table>`
        ));

        // Orphans
        const orphans = r.orphans || [];
        cards.push(buildReportCard(
            '🔍 Orphan pages', orphans.length, orphans.length === 0,
            orphans.length === 0
                ? '<div class="empty">No orphan pages.</div>'
                : `<table><thead><tr><th>URL</th></tr></thead><tbody>${
                    orphans.slice(0, 100).map(o => `<tr><td>${escHtml(o.url)}</td></tr>`).join('')
                }</tbody></table>`
        ));

        // Duplicates
        const duplicates = r.duplicates || [];
        cards.push(buildReportCard(
            '🪞 Duplicates', duplicates.length, duplicates.length === 0,
            duplicates.length === 0
                ? '<div class="empty">No duplicate URLs found.</div>'
                : `<table><thead><tr><th>Type</th><th>Group / Hash</th><th>Count</th></tr></thead><tbody>${
                    duplicates.slice(0, 50).map(g => `<tr><td>${escHtml(g.type)}</td><td>${escHtml((g.canonical || g.contentHash || '').slice(0, 60))}</td><td>${g.urls.length}</td></tr>`).join('')
                }</tbody></table>`
        ));

        // Link analysis
        const linkAnalysis = r.linkAnalysis || [];
        cards.push(buildReportCard(
            '🕸️ Link analysis', linkAnalysis.length, linkAnalysis.length === 0,
            linkAnalysis.length === 0
                ? '<div class="empty">No link data.</div>'
                : `<table><thead><tr><th>URL</th><th>Depth</th><th>↗ In</th><th>↘ Out</th><th>Status</th></tr></thead><tbody>${
                    linkAnalysis.slice(0, 200).map(l => `<tr><td>${escHtml(l.url)}</td><td>${l.depth}</td><td>${l.inDegree}</td><td>${l.internalLinkCount}</td><td>${l.status || ''}</td></tr>`).join('')
                }</tbody></table>`
        ));

        target.innerHTML = cards.join('');
    }

    // ─── wire up tab strip ────────────────────────────────────────────────
    function switchResultTab(tab) {
        activeTab = tab;
        const tabs = document.querySelectorAll('.sitemap-result-tab');
        tabs.forEach(t => t.classList.toggle('active', t.dataset.tab === tab));
        document.querySelectorAll('.sitemap-result-panel').forEach(p => {
            p.classList.toggle('active', p.dataset.tab === tab);
        });
    }

    document.addEventListener('click', e => {
        const tab = e.target.closest('.sitemap-result-tab');
        if (tab && tab.dataset.tab) {
            switchResultTab(tab.dataset.tab);
        }
    });

    // ─── render reports + summary after a crawl finishes ──────────────────
    async function refreshAfterCrawl(scope, result) {
        lastSiteUrl = result && (result.siteUrl || (result.stats && result.stats.startUrl)) || lastSiteUrl;
        lastStats   = (result && result.stats) || lastStats;
        lastXml     = (result && result.xml) || lastXml;
        lastSavedId = (result && result.savedId) || lastSavedId;
        if (result && result.clientId) lastClientId = result.clientId;

        // Show export toolbar + tab strip once we have a savedId (client mode AND
        // quick mode after B9). The old version only flipped these for 'client'.
        if (lastSavedId) {
            if ($('smQuickExportToolbar')) $('smQuickExportToolbar').style.display = 'inline-flex';
            if ($('smQuickResultTabs'))    $('smQuickResultTabs').style.display    = '';
        }

        // Render the report tabs (URLs, Images, Videos, News, Reports) when saved
        if (lastSavedId && lastClientId) {
            try {
                const res = await fetch(`/api/sitemap/reports/${lastClientId}/${lastSavedId}`);
                if (res.ok) {
                    const data = await res.json();
                    if (data.success && data.reports) {
                        setReports(data.reports);
                        // Build image/video/news arrays from the saved pageDetails — the
                        // reports endpoint returns the full per-page record so we can
                        // pull these from the DB rather than relying on the in-memory
                        // window._lastImageData / window._lastVideoData / window._lastNewsData
                        // (which was the B11 bug — those variables were never written).
                        const images = [];
                        const videos = [];
                        const news   = [];
                        for (const url of Object.keys(data.reports.pageDetails || {})) {
                            const d = data.reports.pageDetails[url];
                            if (Array.isArray(d.images)) {
                                for (const i of d.images) images.push({ loc: i.loc, title: i.title });
                            }
                            if (Array.isArray(d.videos)) {
                                for (const v of d.videos) videos.push(v);
                            }
                            if (Array.isArray(d.news)) {
                                for (const n of d.news) news.push(n);
                            }
                        }
                        setImageData(images);
                        setVideoData(videos);
                        setNewsData(news);
                        renderImageGrid($('smQuickImageGrid'), images);
                        renderVideoList($('smQuickVideoList'), videos);
                        renderNewsList($('smQuickNewsList'),   news);
                        renderReports($('smQuickReportsContent'), { reports: data.reports });
                        switchResultTab(activeTab);
                    }
                }
                const vres = await fetch('/api/sitemap/validate', {
                    method: 'POST', headers: { 'Content-Type': 'application/json' },
                    body: JSON.stringify({ id: lastSavedId })
                });
                if (vres.ok) {
                    const vdata = await vres.json();
                    if (vdata.success && vdata.validation) {
                        const reportsBox = $('smQuickReportsContent');
                        renderReports(reportsBox, { reports: (window._lastReports || {}), validation: vdata.validation });
                    }
                }
            } catch (err) { /* ignore */ }
        }
    }

    function collectImages()  { return (window._lastImageData || []); }
    function collectVideos()  { return (window._lastVideoData || []); }
    function collectNews()    { return (window._lastNewsData  || []); }

    // ─── expose helpers for sitemap.js to call ────────────────────────────
    window.sitemapPro = {
        renderSummary,
        renderImageGrid,
        renderVideoList,
        renderNewsList,
        renderReports,
        refreshAfterCrawl,
        buildRobotsTxt,
        setLastContext(id, savedId, siteUrl) {
            lastClientId = id;
            lastSavedId  = savedId;
            lastSiteUrl  = siteUrl;
        },
        getLastContext() { return { clientId: lastClientId, savedId: lastSavedId, siteUrl: lastSiteUrl, xml: lastXml, stats: lastStats }; },
        setReports(r) { window._lastReports = r; },
        setImageData(d) { window._lastImageData = d; },
        setVideoData(d) { window._lastVideoData = d; },
        setNewsData(d)   { window._lastNewsData = d; },
        switchResultTab,
    };
})();
